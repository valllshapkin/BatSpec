set -e

# Функция для поиска строк с Error в директории
search_error() {
    local dir_path="$1"
    
    # Проверяем, передан ли аргумент
    if [ -z "$dir_path" ]; then
        echo "Ошибка: Не указан путь до директории"
        echo "Использование: search_error <путь_до_директории>"
        return 1
    fi
    
    # Проверяем, существует ли директория
    if [ ! -d "$dir_path" ]; then
        echo "Ошибка: Директория '$dir_path' не существует"
        return 1
    fi
    
    echo "Поиск строк с 'Error' в директории: $dir_path"
    echo "----------------------------------------"
    
    # Ищем строки с Error (регистронезависимо)
    grep -r -n "Error" "$dir_path" 2>/dev/null
    
    # Проверяем результат поиска
    if [ $? -eq 0 ]; then
        echo "----------------------------------------"
        echo "Поиск завершён"
    else
        echo "Строки с 'Error' не найдены"
    fi
}

# Вызов функции (раскомментируйте для использования)
search_error "$ScriptDir/../__locale__"